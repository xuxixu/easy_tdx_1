"""技术指标引擎 — TA-Lib（替代 MyTT）。

本包是 easy-tdx 唯一的指标计算引擎，由三层组成：

===========================  ====================================================
层                           内容
===========================  ====================================================
:mod:`~easy_tdx.ta.core`     0/1 级公式原语（MA/EMA/REF/HHV/CROSS …），
                             通达信方言，公式引擎 ``easy_tdx.formula`` 的词汇表
:mod:`~easy_tdx.ta.talib_ind`  TA-Lib 原生指标适配（MACD/RSI/BOLL/KDJ/ATR …）
:mod:`~easy_tdx.ta.chinese`    TA-Lib 未覆盖的中式指标（BIAS/XSII/捉妖 …）
===========================  ====================================================

用法与旧版完全一致（只是包名从 ``easy_tdx.MyTT`` 变成 ``easy_tdx.ta``）::

    from easy_tdx import ta

    dif, dea, hist = ta.MACD(close, SHORT=12, LONG=26, M=9)
    k, d, j = ta.KDJ(close, high, low, 9, 3, 3)

数值口径以 **TA-Lib 为准**，与旧 MyTT 的差异见
:mod:`~easy_tdx.ta.talib_ind` 的模块文档（MACD 柱不再乘 2、RSI 默认 14、
WR 改用 WILLR 的 -100~0 刻度等）。TA-Lib 是**硬依赖**（``pip install
easy-tdx`` 即包含），未安装时导入本包直接报错而非静默降级。
"""

